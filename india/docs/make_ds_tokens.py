#!/usr/bin/env python3
"""Generate the design system's token stylesheet from its tokens.json.

Why this exists rather than just using the system's own `project/tokens.css`:
that file is generated by the design-system page on save, and as of version
1790196341-9f29 it is stale. It carries no `[data-theme="dark"]` block and none
of the heading-scale classes, although `tokens.json` defines a dark value for 86
colour tokens and a full "Titulos (fora da plataforma)" group. A consumer that
inlines the published tokens.css gets a report that cannot go dark and has no
headings above 18px.

So we read the source of truth and emit the stylesheet ourselves. Delete this
script the day the design system republishes a current tokens.css.

One deliberate addition: the artifact host leaves the root element unstamped
when the viewer's theme is "system", and only `prefers-color-scheme` separates
light from dark there. The design system keys dark off `[data-theme="dark"]`
alone, so the dark block is emitted a second time inside a media query guarded
by `:root:not([data-theme="light"])` — which makes all three states resolve.

    python docs/make_ds_tokens.py --tokens <dir>/tokens.json --out <dir>/ds/tokens.css
"""

import argparse
import json
import pathlib

# Families whose entries are plain {name, value} lists.
FLAT = ["spacing", "radius", "shadow", "border", "gradient", "transition",
        "breakpoint", "zIndex", "fontWeight", "fontSize", "lineHeight"]


def resolve(value):
    """`{other-token}` is an alias in tokens.json; in CSS it has to be a var()."""
    if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
        return "var(--%s)" % value[1:-1]
    return value


def decls(pairs, indent="  "):
    return "\n".join("%s--%s: %s;" % (indent, name, resolve(value)) for name, value in pairs)


def build(tokens: dict) -> str:
    colour = tokens["color"]["tokens"]

    light, dark = [], []
    for tok in colour:
        value = tok.get("value")
        if isinstance(value, dict):
            if value.get("light"):
                light.append((tok["name"], value["light"]))
            if value.get("dark"):
                dark.append((tok["name"], value["dark"]))
        elif value:
            light.append((tok["name"], value))

    flat = []
    for family in FLAT:
        for tok in tokens.get(family, {}).get("tokens", []):
            value = tok.get("value")
            if isinstance(value, dict):
                value = value.get("light")
            if value is not None:
                flat.append((tok["name"], value))

    type_block = tokens["type"]
    families = [("font-%s" % k, v) for k, v in type_block.get("families", {}).items()]

    out = ["/* Generated from the MapBiomas design system tokens.json by",
           "   docs/make_ds_tokens.py. Do not edit by hand. */",
           "",
           ":root, [data-theme=\"light\"] {",
           decls(light),
           decls(flat),
           decls(families),
           "}",
           ""]

    dark_body = decls(dark)
    out += ["[data-theme=\"dark\"] {", dark_body, "}", "",
            "/* The host stamps nothing when the viewer's theme is \"system\". */",
            "@media (prefers-color-scheme: dark) {",
            "  :root:not([data-theme=\"light\"]) {",
            decls(dark, indent="    "),
            "  }",
            "}",
            ""]

    # The heading scale: real classes, one per style, as the README describes.
    for group in type_block.get("groups", []):
        if "tulos" not in group.get("name", ""):
            continue
        stack = type_block["families"].get(group.get("family", "sans"), "sans-serif")
        out.append("/* %s */" % group["name"])
        for style in group.get("styles", []):
            rules = [
                "  font-family: %s;" % stack,
                "  font-size: %s;" % style["fontSize"],
                "  line-height: %s;" % style["lineHeight"],
                "  font-weight: %s;" % style["fontWeight"],
            ]
            if style.get("letterSpacing"):
                rules.append("  letter-spacing: %s;" % style["letterSpacing"])
            rules.append("  margin: 0;")
            out.append(".%s {\n%s\n}" % (style["name"], "\n".join(rules)))
        out.append("")

    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tokens", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args()

    css = build(json.loads(args.tokens.read_text(encoding="utf-8")))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(css, encoding="utf-8")
    print("%s  %.1f KB" % (args.out, len(css.encode()) / 1024))


if __name__ == "__main__":
    main()
