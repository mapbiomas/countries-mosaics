#!/usr/bin/env python3
"""Fold the delivery report into one self-contained HTML file.

The published artifact is a multi-file page: `index.html` plus `ds/*` (the
MapBiomas design system bundle) and `img/*` (the mosaic imagery).  That shape is
right for the web — the browser caches the 1 MB bundle and lazy-loads 46 images —
but it cannot be committed usefully, because the page alone does not render.

This script inlines every stylesheet, script and image as a data URI so the
result opens by double-click, survives being e-mailed, and can be versioned as a
single blob.  It is the file the repository keeps.

    python docs/build_report.py \
        --src   /path/to/report/index.html \
        --assets /path/to/report \
        --out   docs/delivery_report.standalone.html

`--assets` is the directory that `ds/` and `img/` sit in — the same directory the
artifact was published from.  Regenerate the imagery first with
`docs/make_report_thumbs.py` if it is not on disk.

What the report must contain, and where each number comes from, is written down
in `docs/REPORT.md`.  Read that before changing the page.
"""

import argparse
import base64
import mimetypes
import pathlib
import re
import sys

# The artifact platform wraps a published page in a skeleton that supplies the
# charset and viewport.  A standalone file gets no skeleton, so it carries its
# own head.  The charset is not cosmetic: the design-system bundle contains
# non-ASCII character ranges inside regular expressions, and a browser that
# decodes it as latin-1 raises "Invalid regular expression: range out of order"
# and the page never renders.
HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- Self-contained build of the India mosaics v2 delivery report.
     Generated by docs/build_report.py — edit the source page, not this file.
     Published version: https://claude.ai/artifact/UC6xhNbzn6NaY5RFFaojPC -->
<style>
  :root { padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
  body { margin: 0; font: 14px system-ui, sans-serif; background: #fafaf9; }
  img { max-width: 100%; }
  [hidden] { display: none !important; }
</style>
"""

TAIL = "\n</body>\n</html>\n"

LINK_RE = re.compile(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s*>', re.I)
SCRIPT_RE = re.compile(r'<script\s+src="([^"]+)"\s*>\s*</script>', re.I)
# src: 'img/NAME.jpg'  /  src: "img/NAME.jpg"  — the page builds these in JS,
# so they are string expressions, not plain attributes.
JS_SRC_RE = re.compile(r"""(['"])((?:img|ds)/[^'"]+)\1""")


def data_uri(path: pathlib.Path) -> str:
    kind, _ = mimetypes.guess_type(path.name)
    if kind is None:
        kind = "application/octet-stream"
    return "data:%s;base64,%s" % (kind, base64.b64encode(path.read_bytes()).decode("ascii"))


def inline(src: pathlib.Path, assets: pathlib.Path) -> str:
    html = src.read_text(encoding="utf-8")
    used: set[pathlib.Path] = set()

    def resolve(ref: str) -> pathlib.Path:
        p = (assets / ref).resolve()
        if not p.is_relative_to(assets.resolve()):
            raise SystemExit("refusing to inline a path outside the asset root: %s" % ref)
        if not p.exists():
            raise SystemExit(
                "missing asset: %s\n"
                "  regenerate the imagery with docs/make_report_thumbs.py, or point\n"
                "  --assets at the directory the artifact was published from." % p
            )
        used.add(p)
        return p

    # A stylesheet may itself pull a webfont; keep the @import, it needs the network.
    def css(m):
        return "<style>\n%s\n</style>" % resolve(m.group(1)).read_text(encoding="utf-8")

    def js(m):
        body = resolve(m.group(1)).read_text(encoding="utf-8")
        if "</script" in body.lower():
            raise SystemExit("script %s contains a closing tag and cannot be inlined" % m.group(1))
        return "<script>\n%s\n</script>" % body

    html = LINK_RE.sub(css, html)
    html = SCRIPT_RE.sub(js, html)
    # Image references are built inside the page's own JavaScript.
    html = JS_SRC_RE.sub(lambda m: "%s%s%s" % (m.group(1), data_uri(resolve(m.group(2))), m.group(1)), html)

    leftovers = sorted(set(JS_SRC_RE.findall(html)))
    if leftovers:
        raise SystemExit("unresolved asset references remain: %s" % leftovers)

    print("inlined %d files" % len(used), file=sys.stderr)
    return HEAD + "<body>\n" + html + TAIL


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, type=pathlib.Path, help="the source page (index.html)")
    ap.add_argument("--assets", required=True, type=pathlib.Path, help="directory holding ds/ and img/")
    ap.add_argument("--out", required=True, type=pathlib.Path, help="where to write the standalone file")
    a = ap.parse_args()

    out = inline(a.src, a.assets)
    a.out.write_text(out, encoding="utf-8")
    print("%s  %.2f MB" % (a.out, len(out.encode("utf-8")) / 1e6), file=sys.stderr)


if __name__ == "__main__":
    main()
